// Install (Beta 3.4: only changed files are downloaded). Every entry in FILES ends in "?v=<fingerprint of its contents>". If the previous
// version's cache already holds that exact entry, the file has not changed: it is copied across instead of downloaded. Everything else is
// downloaded with cache: "reload" (skipping the browser's own HTTP cache, so it is really the file on the server), 8 at a time.
// A device updating from a version before 3.4 has no fingerprints yet, so it downloads everything once.
self.addEventListener("install", (e) => {
  e.waitUntil((async () => {
    const fresh = await caches.open(CACHE_VERSION);
    const oldNames = (await caches.keys()).filter((k) => k.startsWith(CACHE_PREFIX) && k !== CACHE_VERSION && k !== MODELS_CACHE);
    const olds = await Promise.all(oldNames.map((k) => caches.open(k)));
    const queue = FILES.slice();
    const one = async (f) => {
      const req = new Request(f);
      if (await fresh.match(req)) return;                                  // already here (an earlier, interrupted install)
      for (const c of olds) {
        const hit = await c.match(req);                                    // exact match: same file, same fingerprint
        if (hit) { await fresh.put(req, hit); return; }
      }
      const res = await fetch(new Request(f, { cache: "reload" }));
      if (!res.ok) throw new Error("Could not download " + f + " (" + res.status + ")");
      await fresh.put(req, res);
    };
    await Promise.all(Array.from({ length: 8 }, async () => { while (queue.length) await one(queue.shift()); }));
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith(CACHE_PREFIX) && k !== CACHE_VERSION && k !== MODELS_CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Cache-first. ignoreSearch lets any ?query on the page address match the cached page.
self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET") return;
  // Stable only: leave anything under beta/ alone, so the network and the beta service worker handle it.
  if (OTHER_CHANNEL_FOLDER &&
      new URL(e.request.url).pathname.startsWith(new URL(OTHER_CHANNEL_FOLDER, self.registration.scope).pathname)) return;
  // Object recognition files (vendor/ and models/): cache-first from the models cache; on a miss fetch once and keep a copy.
  const scopePath = new URL(self.registration.scope).pathname;
  const path = new URL(e.request.url).pathname;
  if (path.startsWith(scopePath + "vendor/") || path.startsWith(scopePath + "models/")) {
    e.respondWith(caches.open(MODELS_CACHE).then((cache) => cache.match(e.request.url).then((hit) => hit || fetch(e.request).then((res) => {
      if (res.ok && res.status === 200) cache.put(e.request.url, res.clone());
      return res;
    }))));
    return;
  }
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request))
  );
});
