// cache: "reload" skips the browser's own HTTP cache, so a new version always installs the files that are really on the server.
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE_VERSION).then((c) => c.addAll(FILES.map((f) => new Request(f, { cache: "reload" })))).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith(CACHE_PREFIX) && k !== CACHE_VERSION).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Cache-first. ignoreSearch lets any ?query on the page address match the cached page.
self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET") return;
  // Stable only: leave anything under beta/ alone, so the network and the beta service worker handle it.
  if (OTHER_CHANNEL_FOLDER &&
      new URL(e.request.url).pathname.startsWith(new URL(OTHER_CHANNEL_FOLDER, self.registration.scope).pathname)) return;
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request))
  );
});
